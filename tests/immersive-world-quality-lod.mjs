import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { createServer } from 'vite';
import { chromium } from '@playwright/test';
const server = await createServer({ server: { host: '127.0.0.1', port: 0 } });
await server.listen();
const browser = await chromium.launch({ headless: true, args: ['--enable-webgl', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const origin = `http://127.0.0.1:${server.httpServer.address().port}`;
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 }, serviceWorkers: 'block', reducedMotion: 'reduce' });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${origin}/immersive/index.html`);
  await page.waitForFunction(() => window.immersive?.world);
  const initial = await page.evaluate(() => window.immersive.world.getState());
  assert.equal(initial.renderedIslandCount, 22);
  assert.equal(initial.preparedIslandCount, 1, 'only the arrival island allocates full scenes');
  assert.equal(initial.detailedIslandCount, 1);
  assert.ok(initial.simplifiedIslandCount > 0, 'nearby islands have a distinct middle model');
  assert.ok(initial.silhouetteIslandCount > 0, 'far islands remain low silhouettes');
  assert.equal(initial.detailedIslandCount + initial.simplifiedIslandCount + initial.silhouetteIslandCount, 22);
  await page.evaluate(() => {
    const api = window.immersive;
    api.world.setRecommendations(api.data.articleGraph.filter(edge => edge.sourceArticleId === api.world.getState().current));
    const target = api.world.getState().recommendations[0]?.targetArticleId;
    if (target) api.world.preview(target);
  });
  assert.equal(await page.evaluate(() => window.immersive.world.getState().preparedIslandCount), 1, 'recommendations and hover do not allocate full scenes');
  await page.evaluate(() => {
    const api = window.immersive;
    api.world.setReducedMotion(false);
    api.world.focus('P04', { animate: true });
    api.world.setActive(false);
  });
  const journey = await page.evaluate(() => window.immersive.world.getState());
  assert.equal(journey.preparedIslandCount, 2, 'navigation prepares destination before arrival');
  assert.equal(journey.detailedIslandCount, 2);
  await page.evaluate(() => window.immersive.world.cancelTransition());
  assert.equal(await page.evaluate(() => window.immersive.world.getState().current), initial.current);
  await page.evaluate(() => { const w = window.immersive.world; w.focus('P04', { animate: true }); w.skipTransition(); });
  assert.equal(await page.evaluate(() => window.immersive.world.getState().transitioning), false);
  await page.evaluate(() => { const api = window.immersive; api.world.setReducedMotion(true); api.visit(api.data.islands[0].articleId, null, false); });
  if (await page.locator('#explore-tip').isVisible()) await page.locator('#hide-explore-tip').click();
  await page.locator('#interact').click();
  await page.locator('#game-controls').getByRole('button', { name: '把資訊放上證據桌', exact: true }).click();
  await page.locator('#game-after:not([hidden])').waitFor();
  const before = await page.evaluate(() => window.immersive.world.getState().interaction);
  await page.evaluate(() => { const w = window.immersive.world; w.focus('A03', { animate: false }); w.focus('I01', { animate: false }); });
  assert.deepEqual(await page.evaluate(() => window.immersive.world.getState().interaction), before, 'lazy revisit retains completed source props and result');
  await page.locator('#replay').click();
  assert.equal(await page.evaluate(() => window.immersive.world.getState().interaction.baselineRestored), true);
  await page.evaluate(() => { const api = window.immersive; for (const island of api.data.islands) api.world.focus(island.articleId, { animate: false }); });
  const all = await page.evaluate(() => window.immersive.world.getState());
  assert.equal(all.preparedIslandCount, 22, 'every full authored island remains available');
  assert.equal(all.detailedIslandCount, 1);
  assert.equal(errors.length, 0, errors.join('\n'));
  const resource = await page.evaluate(() => { const w = window.immersive.world; const before = w.getRenderState(), labels = w.getLabelResourceState(); w.dispose(); w.dispose(); return { before, labels, after: w.getRenderState() }; });
  assert.equal(resource.labels.uniqueMaterialCount, resource.labels.count, 'each live label keeps its own material');
  assert.equal(resource.labels.untrackedMaterialCount, 0, 'speech deletion cannot overwrite another live label disposal owner');
  assert.equal(resource.after.disposed, true);
  assert.equal(resource.after.ownedTextureCount, 0);
  assert.equal(resource.after.ownedGeometryCount, 0);
  assert.equal(resource.after.ownedMaterialCount, 0);
  assert.equal(resource.after.textureCount, 0, 'renderer releases the shadow-map texture as well as owned textures');
  assert.ok(resource.after.releasedResources.textures > 0);
  await mkdir('test-results/immersive-world-quality', { recursive: true });
  await writeFile('test-results/immersive-world-quality/lod.json', JSON.stringify({ initialLOD: initial.islandLOD, visitedCount: all.visited.length, resource, errors }, null, 2));
  console.log('Source LOD lifecycle passed. Evidence in test-results/immersive-world-quality/lod.json');
} finally { await browser.close(); await server.close(); }
