import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { createServer } from 'vite';
import { chromium } from '@playwright/test';
const output = 'test-results/immersive-world-quality';
await mkdir(output, { recursive: true });
const server = await createServer({ server: { host: '127.0.0.1', port: 0, hmr: false } }); await server.listen();
const browser = await chromium.launch({ headless: true, args: ['--enable-webgl', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const origin = `http://127.0.0.1:${server.httpServer.address().port}`;
const records = [], errors = [];
const routesOnly = process.env.QUALITY_ROUTES_ONLY === '1';
const previewsOnly = process.env.QUALITY_PREVIEWS_ONLY === '1';
const previewWidths = process.env.QUALITY_PREVIEW_WIDTH ? [Number(process.env.QUALITY_PREVIEW_WIDTH)] : [1280, 390];
try {
  for (const width of routesOnly || previewsOnly ? [] : [1280, 390]) {
    const page = await browser.newPage({ viewport: { width, height: width === 390 ? 844 : 800 }, reducedMotion: 'reduce', serviceWorkers: 'block' });
    page.setDefaultTimeout(15000);
    page.on('pageerror', e => errors.push(e.message));
    await page.goto(`${origin}/immersive/index.html`);
    await page.waitForFunction(() => window.immersive?.world);
    if (await page.locator('#explore-tip').isVisible()) await page.locator('#hide-explore-tip').click();
    const read = () => page.evaluate(() => window.immersive.world.getState());
    const target = async (id, last = false) => {
      const targets = await page.evaluate(id => window.immersive.world.getMicroeventTargets().filter(t => t.objectId === id), id);
      assert.ok(targets.length, `target ${id} exists`);
      const t = last ? targets.at(-1) : targets[0];
      await page.mouse.click(t.screen.x, t.screen.y);
    };
    await page.evaluate(() => { const w = window.immersive.world; w.cancelArrival(); w.setReducedMotion(false); });
    await target('studio-door', true);
    await page.waitForFunction(() => window.immersive.world.getState().microevent?.elapsed >= .78);
    await page.evaluate(() => window.immersive.world.setActive(false));
    const contact = (await read()).microevent;
    assert.equal(contact.kind, 'studio-door'); assert.ok(contact.handDistance < .02, `hand reaches handle ${contact.handDistance}`);
    assert.equal(contact.hingeAngle, 0, 'door waits for hand contact');
    await page.locator('#world').screenshot({ path: `${output}/${width}-door-contact.png` });
    await page.evaluate(() => window.immersive.world.setActive(true));
    await page.waitForFunction(() => window.immersive.world.getState().microevent?.complete);
    const door = (await read()).microevent; assert.ok(door.hingeAngle < -1); assert.ok(door.handDistance < .02);
    await page.locator('#world').screenshot({ path: `${output}/${width}-door-open.png` });
    await target('studio-chair');
    await page.waitForFunction(() => window.immersive.world.getState().microevent?.complete);
    const chair = (await read()).microevent; assert.equal(chair.kind, 'studio-chair'); assert.ok(Math.abs(chair.hipY - chair.seatTop) < .01); assert.equal(chair.contact, true);
    await page.locator('#world').screenshot({ path: `${output}/${width}-chair-seated.png` });
    await page.evaluate(() => { const api = window.immersive; api.world.setReducedMotion(true); api.visit(api.data.islands.find(i => i.id === 'M05').articleId, null, false); api.world.cancelArrival(); });
    assert.equal((await read()).microevent, null, 'leaving furniture cancels actor support pose');
    const cultureBefore = (await read()).cultureWindow;
    assert.ok(cultureBefore.resistance.every(r => r.y + r.height / 2 < cultureBefore.waterY));
    await page.locator('#world').screenshot({ path: `${output}/${width}-M05-underwater.png` });
    await target('culture-resistance-1');
    const cultureAfter = (await read()).cultureWindow; assert.equal(cultureAfter.selected, 1); assert.ok(cultureAfter.resistance[1].y > cultureBefore.resistance[1].y);
    await page.locator('#world').screenshot({ path: `${output}/${width}-M05-surface-resistance.png` });
    await page.evaluate(() => { const w = window.immersive.world; w.playArrival({ source: 'bell' }); });
    assert.deepEqual((await read()).arrivalEvent.history, ['cause', 'action', 'reaction']);
    const cultureChoices = [];
    for (const choice of ['fear', 'guidance', 'silo']) {
      await page.locator('#interact').click();
      await page.locator('#scene-choice').selectOption(choice);
      for (const [index, value] of ['data', 'estimate', 'inference', 'unknown'].entries()) await page.locator('#game-controls select').nth(index + 1).selectOption(value);
      await page.locator('#game-controls').getByRole('button', { name: '把資訊放上證據桌', exact: true }).click();
      await page.locator('#game-after:not([hidden])').waitFor();
      const result = (await read()).interaction;
      assert.equal(result.scenarioChoice, choice); assert.ok(result.scenarioObjects.length > 0);
      cultureChoices.push(result); await page.locator('#game form button').click();
    }
    records.push({ width, cultureChoices });
    await page.evaluate(() => { const api = window.immersive; api.visit(api.data.islands.find(i => i.id === 'A03').articleId, null, false); api.world.cancelArrival(); });
    const graph = (await read()).knowledgeGraph; assert.equal(graph.nodes.length, 4); assert.equal(graph.links.length, 3); assert.ok(graph.source.paragraphs.length > 0);
    await page.locator('#world').screenshot({ path: `${output}/${width}-A03-before.png` });
    for (const id of ['facts', 'voice', 'answer', 'experience']) { await target(`knowledge-${id}`); assert.equal((await read()).knowledgeGraph.selected, id); assert.equal(await page.locator('#game').evaluate(e => e.open), false); }
    await page.locator('#world').screenshot({ path: `${output}/${width}-A03-knowledge.png` });
    records.push({ width, contact, door, chair, cultureBefore, cultureAfter, graph });
    await page.close();
  }
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 }, reducedMotion: 'reduce', serviceWorkers: 'block' });
  page.setDefaultTimeout(15000);
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(`${origin}/immersive/index.html`); await page.waitForFunction(() => window.immersive?.world);
  if (await page.locator('#explore-tip').isVisible()) await page.locator('#hide-explore-tip').click();
  for (const [from, to, carryKind] of previewsOnly ? [] : [['P01', 'P04', 'photo-evidence-bridge'], ['P05', 'A06', 'product-service-journey'], ['M01', 'M03', 'model-limits-scale']]) {
    console.log('Route', from, to); page.setDefaultTimeout(15000);
    const ids = await page.evaluate(([from, to]) => ({ from: window.immersive.data.islands.find(i => i.id === from).articleId, to: window.immersive.data.islands.find(i => i.id === to).articleId }), [from, to]);
    await page.locator('#map-toggle').click();
    await page.locator('#article-list button').filter({ hasText: `${from} ·` }).click();
    await page.evaluate(() => window.immersive.world.skipTransition());
    if (await page.locator('#motion').isChecked()) { await page.locator('#settings-toggle').click(); await page.locator('#motion').uncheck(); await page.locator('#settings-toggle').click(); }
    await page.locator('#read').click();
    const expected = await page.evaluate(({ from, to }) => window.immersive.data.articleGraph.find(e => e.sourceArticleId === from && e.targetArticleId === to), ids);
    const recommendation = page.locator('#recommendations button').filter({ hasText: expected.transitionQuestion });
    await recommendation.waitFor();
    assert.ok((await recommendation.innerText()).includes(expected.editorialReason));
    await page.evaluate(() => { const w = window.immersive.world; w.setReducedMotion(false); w.setArrivalEnabled(true); });
    await recommendation.click();
    await page.waitForFunction(() => window.immersive.world.getState().departure?.progress > .8);
    await page.evaluate(() => window.immersive.world.setActive(false));
    const source = await page.evaluate(() => window.immersive.world.getState());
    assert.equal(source.departure.pair, `${from}-${to}`); assert.equal(source.current, ids.from);
    await page.locator('#world').screenshot({ path: `${output}/1280-${from}-${to}-departure.png` });
    await page.evaluate(() => window.immersive.world.setActive(true));
    await page.waitForFunction(() => { const s = window.immersive.world.getState(); return s.carry.visible && s.carry.morph > .15; });
    await page.evaluate(() => window.immersive.world.setActive(false));
    const carry = await page.evaluate(() => window.immersive.world.getState().carry); assert.equal(carry.kind, carryKind);
    await page.locator('#world').screenshot({ path: `${output}/1280-${from}-${to}-carry.png` });
    await page.evaluate(() => window.immersive.world.setActive(true));
    await page.waitForFunction(id => { const s = window.immersive.world.getState(); return s.current === id && s.arrivalEvent?.phase === 'cause'; }, ids.to);
    const arrival = await page.evaluate(() => window.immersive.world.getState());
    assert.equal(arrival.departure, null); assert.equal(arrival.arrivalEvent.articleId, ids.to);
    await page.locator('#world').screenshot({ path: `${output}/1280-${from}-${to}-arrival.png` });
    await page.locator('#return-source').click();
    await page.waitForFunction(id => window.immersive.world.getState().current === id && !window.immersive.world.getState().transitioning, ids.from);
    const returned = await page.evaluate(() => window.immersive.world.getState());
    assert.equal(returned.current, ids.from); assert.equal(returned.departure, null);
    records.push({ route: [from, to], expected, source: source.departure, carry, arrival: arrival.arrivalEvent, returned: returned.current });
  }
  for (const width of routesOnly ? [] : previewWidths) for (const [from, to] of [['I02', 'P01'], ['P04', 'P05'], ['M02', 'M03']]) {
    console.log('Preview', width, to);
    const previewPage = await browser.newPage({ viewport: { width, height: width === 390 ? 844 : 800 }, reducedMotion: 'reduce', serviceWorkers: 'block' });
    previewPage.setDefaultTimeout(12000);
    previewPage.on('pageerror', e => errors.push(e.message));
    await previewPage.goto(`${origin}/immersive/index.html`); await previewPage.waitForFunction(() => window.immersive?.world);
    if (await previewPage.locator('#explore-tip').isVisible()) await previewPage.locator('#hide-explore-tip').click();
    const ids = await previewPage.evaluate(([from, to]) => ({ from: window.immersive.data.islands.find(i => i.id === from).articleId, to: window.immersive.data.islands.find(i => i.id === to).articleId }), [from, to]);
    await previewPage.locator('#map-toggle').click();
    await previewPage.locator('#article-list button').filter({ hasText: `${from} ·` }).click();
    await previewPage.locator('#read').click();
    await previewPage.locator('#note').fill(`Draft retained during ${to} preview`);
    const before = await previewPage.evaluate(() => window.immersive.world.getState().preparedIslandCount);
    const expected = await previewPage.evaluate(({ from, to }) => window.immersive.data.articleGraph.find(e => e.sourceArticleId === from && e.targetArticleId === to), ids);
    const button = previewPage.locator('#recommendations button').filter({ hasText: expected.transitionQuestion });
    if (width === 390) { await previewPage.mouse.move(10, 10); await previewPage.locator('#note').focus(); await previewPage.keyboard.press('Tab'); assert.equal(await button.evaluate(e => document.activeElement === e), true); } else await button.hover();
    const hovered = await previewPage.evaluate(() => window.immersive.world.getState());
    const target = hovered.recommendations.find(route => route.targetArticleId === ids.to);
    if (!target.previewVisible) await writeFile(`${output}/preview-failure.json`, JSON.stringify(await previewPage.evaluate(() => ({ state: window.immersive.world.getState(), bodyPreview: document.body.dataset.islandPreview, readerOpen: document.querySelector('#reader').open })), null, 2));
    assert.equal(target.previewVisible, true); assert.equal(target.previewKind, to); assert.ok(target.previewMeshes >= 3);
    assert.equal(hovered.preparedIslandCount, before, 'semantic hover does not build full destination');
    await previewPage.locator('#world').screenshot({ path: `${output}/${width}-${to}-DOM-hover.png` });
    const scrollBeforeClear = await previewPage.locator('#reader').evaluate(e => e.scrollTop);
    await button.evaluate(e => e.blur());
    await previewPage.mouse.move(10, 10);
    const scrollAfterClear = await previewPage.locator('#reader').evaluate(e => e.scrollTop);
    assert.ok(Number.isFinite(scrollAfterClear));
    assert.equal(await previewPage.locator('body').getAttribute('data-island-preview'), null);
    assert.equal(await previewPage.locator('#note').inputValue(), `Draft retained during ${to} preview`);
    const clearedFrame = await previewPage.evaluate(() => window.immersive.world.getRenderState().renderedFrames);
    await previewPage.waitForTimeout(100);
    assert.equal(await previewPage.evaluate(() => window.immersive.world.getRenderState().renderedFrames), clearedFrame, 'reading remains GPU paused after bounded hover render');
    await previewPage.keyboard.press('Escape');
    assert.equal(await previewPage.locator('body').getAttribute('data-island-preview'), null);
    records.push({ preview: to, width, before, target, clearedFrame, scrollBeforeClear, scrollAfterClear, draftRetained: true }); await previewPage.close();
  }
  assert.deepEqual(errors, []);
  await writeFile(`${output}/${previewsOnly ? `previews${process.env.QUALITY_PREVIEW_WIDTH ? '-' + process.env.QUALITY_PREVIEW_WIDTH : ''}` : routesOnly ? 'routes' : 'quality'}.json`, JSON.stringify({ records, errors }, null, 2));
  console.log('World quality source browser checks passed');
} finally { await browser.close(); await server.close(); }
