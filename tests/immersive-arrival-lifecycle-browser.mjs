import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { preview } from 'vite';
import { chromium } from '@playwright/test';
const server = await preview({ preview: { host: '127.0.0.1', port: 0 } });
const browser = await chromium.launch({ headless: true, args: ['--enable-webgl', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const origin = `http://127.0.0.1:${server.httpServer.address().port}`;
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 }, reducedMotion: 'reduce', serviceWorkers: 'block' });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${origin}/immersive/index.html`);
  await page.waitForFunction(() => window.immersive?.world);
  if (await page.locator('#explore-tip').isVisible()) await page.locator('#hide-explore-tip').click();
  await page.locator('#interact').click();
  await page.locator('#game-controls').getByRole('button', { name: '把資訊放上證據桌', exact: true }).click();
  await page.locator('#game-after:not([hidden])').waitFor();
  const readResult = () => page.evaluate(() => ({ interaction: window.immersive.world.getState().interaction, progress: structuredClone(window.immersive.progress) }));
  const before = await readResult();
  await page.locator('#game form button').click();
  await page.locator('#replay-arrival').click();
  assert.equal(await page.locator('#game').evaluate(dialog => dialog.open), false, 'bell replay does not open game');
  const after = await readResult();
  assert.deepEqual(after.interaction, before.interaction, 'bell completion restores exact completed choice and geometry');
  assert.deepEqual(after.progress, before.progress, 'bell does not mutate progress or stamps');
  await page.evaluate(() => { const api = window.immersive; api.world.setReducedMotion(false); api.world.playArrival({ source: 'bell' }); });
  assert.ok(await page.evaluate(() => window.immersive.world.getState().arrivalEvent));
  await page.evaluate(() => window.immersive.world.cancelArrival(true));
  assert.deepEqual((await readResult()).interaction, before.interaction, 'cancel restores result');
  await page.evaluate(() => { const api = window.immersive; api.visit(api.data.islands[1].articleId, null, false); api.visit(api.data.islands[0].articleId, null, false); });
  assert.equal(await page.evaluate(() => window.immersive.world.getState().arrivalEvent), null, 'revisit preserves completed result');
  assert.deepEqual((await readResult()).interaction, before.interaction);
  await page.evaluate(() => { window.immersive.world.resize(); window.immersive.world.focus(window.immersive.world.getState().current, { animate: false }); });
  assert.equal(await page.evaluate(() => window.immersive.world.getState().arrivalEvent), null, 'same-island sync does not replay');
  assert.equal(errors.length, 0, errors.join('\n'));
  await mkdir('test-results/immersive-arrival-lifecycle', { recursive: true });
  await writeFile('test-results/immersive-arrival-lifecycle/results.json', JSON.stringify({ before, after, errors }, null, 2));
  console.log('built lifecycle passed bell, result preservation, cancellation, revisit and same-island sync');
} finally { await browser.close(); server.httpServer.closeAllConnections?.(); await server.close(); }
