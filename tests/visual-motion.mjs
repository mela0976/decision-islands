import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';

const base = process.env.TEST_URL || 'http://127.0.0.1:4173/';
await mkdir('test-results', { recursive: true });
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto(base);
const canvas = page.locator('.island-world canvas');
await canvas.waitFor();
await page.waitForTimeout(1500);
const initial = await canvas.screenshot();
await page.waitForTimeout(13000);
const rotated = await canvas.screenshot();
assert.notDeepEqual(initial, rotated, 'homepage book tree continues rotating beyond the idle timeout');
await page.locator('#motion').click();
await page.waitForTimeout(200);
const paused = await canvas.screenshot();
await page.waitForTimeout(1100);
assert.deepEqual(paused, await canvas.screenshot(), 'pause holds the rendered scene still');
await page.locator('#motion').click();
await page.waitForTimeout(2000);
assert.notDeepEqual(paused, await canvas.screenshot(), 'motion resumes');
await page.getByRole('button', { name: '啟程，探索 2026' }).click();
await page.getByRole('button', { name: '略過轉場' }).click();
await page.waitForFunction(() => document.body.classList.contains('exploring'));
assert.equal(await page.locator('.island-world').getAttribute('data-phase'), 'islands');
assert.deepEqual(errors, []);
await writeFile('test-results/visual-motion.json', JSON.stringify({ base, checks: ['rotation continues after 13 seconds idle', 'pause freezes canvas', 'resume rotates canvas', 'skip entrance reaches islands'], errors }, null, 2));
console.log('Visual motion: 4 checks passed');
await browser.close();
