import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { preview } from 'vite';
import { chromium } from '@playwright/test';

const output = 'test-results/immersive-character-contact';
await mkdir(output, { recursive: true });
const workerSource = await readFile('public/immersive/sw.js', 'utf8');
const expectedCacheVersion = workerSource.match(/const CACHE_VERSION = '([^']+)'/)?.[1];
assert.ok(expectedCacheVersion, 'immersive worker declares its cache version');
const server = await preview({ preview: { host: '127.0.0.1', port: 0 } });
const browser = await chromium.launch({ headless: true, args: ['--enable-webgl', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const origin = `http://127.0.0.1:${server.httpServer.address().port}`;
const errors = [], checks = [];
const record = name => checks.push({ name, passed: true });
async function chooseCheer(page) {
  await page.evaluate(() => window.immersive.openGame());
  await page.locator('#scene-choice').selectOption('cheer');
  await page.getByRole('button', { name: /翻看舊票根/ }).click();
  await page.getByRole('button', { name: '把這段回憶留在廣場', exact: true }).click();
}
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${origin}/immersive/index.html`);
  await page.waitForFunction(() => window.immersive?.world);
  const ids = await page.evaluate(() => Object.fromEntries(window.immersive.data.islands.map(island => [island.id, island.articleId])));
  await page.evaluate(id => window.immersive.visit(id, null, false), ids.P06);
  await chooseCheer(page);
  await page.locator('#game-read').click();
  await page.locator('#reader[open]').waitFor();
  const paused = await page.evaluate(() => ({ event: window.immersive.world.getCharacterContactState(), active: window.immersive.world.getRenderState().active }));
  assert.equal(paused.active, false);
  await page.waitForTimeout(350);
  assert.equal((await page.evaluate(() => window.immersive.world.getCharacterContactState())).elapsed, paused.event.elapsed);
  await page.keyboard.press('Escape');
  await page.locator('#reader').waitFor({ state: 'hidden' });
  assert(await page.locator('#game[open]').isVisible());
  await page.waitForTimeout(80);
  const resumed = await page.evaluate(() => window.immersive.world.getCharacterContactState());
  assert(resumed.elapsed - paused.event.elapsed < .3);
  record('reading pauses event time and resumes without catching up');
  await page.locator('#compare').click();
  assert.equal(await page.evaluate(() => window.immersive.world.getCharacterContactState()), null);
  assert.equal(await page.evaluate(() => window.immersive.world.getState().interaction.baselineRestored), true);
  await page.locator('#compare').click();
  assert.equal((await page.evaluate(() => window.immersive.world.getCharacterContactState())).effectId, 'P06-cheer');
  record('compare cancels contact and restores the choice baseline');
  await page.locator('#replay').click();
  assert.equal(await page.evaluate(() => window.immersive.world.getCharacterContactState()), null);
  await page.locator('#scene-choice').selectOption('cheer');
  await page.getByRole('button', { name: /翻看舊票根/ }).click();
  await page.getByRole('button', { name: '把這段回憶留在廣場', exact: true }).click();
  assert((await page.evaluate(() => window.immersive.world.getCharacterContactState())).elapsed < 1.2);
  record('replay starts a fresh bounded event');
  await page.evaluate(id => window.immersive.visit(id, null, false), ids.P01);
  assert.equal(await page.evaluate(() => window.immersive.world.getCharacterContactState()), null);
  await page.waitForTimeout(200);
  assert.equal(await page.evaluate(() => window.immersive.world.getCharacterContactState()), null);
  await page.evaluate(id => window.immersive.visit(id, null, false), ids.P06);
  const restored = await page.evaluate(() => window.immersive.world.getCharacterContactState());
  assert.equal(restored.effectId, 'P06-cheer');
  assert.equal(restored.complete, true);
  record('leaving cancels the event and returning restores its supported final pose');
  await page.evaluate(() => window.immersive.world.setReducedMotion(true));
  await chooseCheer(page);
  const reduced = await page.evaluate(() => window.immersive.world.getCharacterContactState());
  assert(reduced.complete && reduced.supported && reduced.owner === null);
  assert.deepEqual(reduced.propPosition, restored.propPosition);
  record('reduced motion presents the same supported final pose immediately');
  await page.evaluate(async () => { await navigator.serviceWorker.ready; });
  await page.waitForFunction(async () => Boolean(await caches.match(new URL('./character-events.js', location.href))), undefined, { timeout: 30000 });
  const snapshot = await page.evaluate(async () => {
    const url = new URL('./character-events.js', location.href);
    const response = await caches.match(url);
    return { status: response.status, text: await response.text(), names: await caches.keys() };
  });
  assert.equal(snapshot.status, 200);
  assert.equal(snapshot.text, await readFile('dist/immersive/character-events.js', 'utf8'));
  assert(snapshot.names.some(name => name.endsWith(expectedCacheVersion)));
  await page.waitForFunction(() => navigator.serviceWorker.controller);
  await context.setOffline(true);
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.waitForFunction(() => window.immersive?.world);
  record('built snapshot caches the exact event module and reloads the complete world offline');
  assert.deepEqual(errors, []);
  await writeFile(`${output}/lifecycle.json`, JSON.stringify({ passed: true, checks, restored, reduced, cacheNames: snapshot.names, errors }, null, 2));
  console.log(JSON.stringify({ passed: true, checks, output }));
  await context.close();
} finally { await browser.close(); await new Promise(resolve => server.httpServer.close(resolve)); }
